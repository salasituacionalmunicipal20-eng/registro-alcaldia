import assert from 'node:assert/strict';
import { edadEn, rangoEdad, registrarMovimiento } from '../juguetes-core.mjs';
const hoy = new Date(2026, 9, 27, 12);
assert.equal(edadEn('2013-10-28', hoy), 12);
assert.equal(edadEn('2013-10-27', hoy), 13);
assert.equal(edadEn('2026-10-27', hoy), 0);
assert.equal(edadEn('2026-10-28', hoy), null);
assert.equal(edadEn('2020-02-30', hoy), null);
assert.equal(edadEn('', hoy), null);
for (const [edad,rango] of [[0,'0 a 2'],[2,'0 a 2'],[3,'3 a 6'],[6,'3 a 6'],[7,'7 a 9'],[9,'7 a 9'],[10,'10 a 12'],[12,'10 a 12'],[13,'']]) assert.equal(rangoEdad(edad),rango);
const base = {id:'m1',tipo:'recepcion',codigo:'MUNECA-1',descripcion:'Muñeca',cantidad:2,presentacion:'caja',responsable:'Responsable',telefono_responsable:'123',dueno:'Dueño',telefono_dueno:'456',fecha:'2026-10-27T00:00:00Z',usuario:'operador',comuna:'',comunidad:''};
const inicial = {};
const recibida = registrarMovimiento(inicial, base).estado;
assert.equal(recibida.inventario['MUNECA-1'].caja,2);
assert.deepEqual(inicial,{});
const salida = {...base,id:'m2',tipo:'salida',cantidad:1,comuna:'Comuna A',comunidad:'La Chivera'};
const despues = registrarMovimiento(recibida,salida).estado;
assert.equal(despues.inventario['MUNECA-1'].caja,1);
assert.equal(despues.movimientos.m2.comunidad,'La Chivera');
assert.match(registrarMovimiento(despues,{...salida,id:'m3',cantidad:2}).error,/existencia/);
assert.match(registrarMovimiento(despues,{...salida,id:'m3',presentacion:'unidad'}).error,/existencia/);
assert.match(registrarMovimiento(despues,{...salida,id:'m3',comunidad:''}).error,/campos/);
assert.match(registrarMovimiento(despues,{...base,id:'m3',descripcion:'Balón'}).error,/código/);
assert.match(registrarMovimiento(despues,{...base,id:'m2'}).error,/registrado/);
console.log('Juguetes: edades, saldos y movimientos verificados.');
